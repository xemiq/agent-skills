def parse_style(style):
    """Parse a draw.io style string into an ordered dict; later keys override earlier ones.
    Bare tokens (e.g. 'ellipse', 'text') are stored with value None."""
    out = {}
    for tok in (style or "").split(";"):
        tok = tok.strip()
        if not tok:
            continue
        if "=" in tok:
            k, v = tok.split("=", 1)
            out[k.strip()] = v.strip()
        else:
            out[tok] = None
    return out


